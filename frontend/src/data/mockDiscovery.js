const normalizeJam = (jam) => ({
  ...jam,
  type: "jam",
  entityKind: "jam_session",
  subtitle: jam.locationName,
  neighborhood: jam.locationName,
  coordinates: { latitude: jam.lat, longitude: jam.lng },
  locationVisibility: "exact",
  approximateRadiusMeters: null,
  ctaLabel: jam.isPrivate ? "Request to Join" : "Join Jam",
  previewCtaLabel: "View Jam",
  accentColor: DISCOVERY_COLORS.jam,
  previewPills: [jam.genre, jam.jamType].filter(Boolean),
  badgeLabel: jam.isLive ? "Live Now" : jam.isPrivate ? "Private" : null,
  metaPrimary: [jam.genre, formatDistanceMiles(jam.distanceMiles)].filter(Boolean).join(" · "),
  metaSecondary: jam.dateTime && jam.dateTime !== "Live Now" ? jam.dateTime : "Open session nearby",
  summary: jam.description,
  heroKicker: "LIVE JAM",
  heroTitle: jam.title.toUpperCase(),
  heroDescription: jam.description,
  detailRows: [
    { label: "Host", value: jam.hostName },
    { label: "Location", value: jam.locationName },
    { label: "Time", value: jam.dateTime },
    { label: "Skill level", value: jam.skillLevel },
    {
      label: "Looking for",
      value: jam.instruments?.length ? jam.instruments.join(", ") : null,
    },
    {
      label: "Capacity",
      value:
        jam.capacity != null && jam.attendeeCount != null
          ? `${jam.attendeeCount} / ${jam.capacity} spots`
          : null,
    },
  ].filter((row) => row.value),
});

